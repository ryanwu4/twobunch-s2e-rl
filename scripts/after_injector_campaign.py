"""Chain after the injector campaign (agreed plan, docs/overnight_2026-10-15.md):

  1. wait for data/injector_full to finish (driver gone + "Done:"); stop if > 5% of rows failed
  2. launch the eval-set campaign (configs/datagen/injector_evalset.yaml at the campaign's fidelity),
     from a worktree pinned to a commit, like the main campaign
  3. preprocess old + new data into processed/xtcav23e_inj_2026-10-15.h5 (37-knob frame
     xtcav23e_l0b2_inj12, XTCAVF, per-sample transmission, backfilled old campaign records)
  4. widen the xtcav23 flow to that frame (exact) -> trained/xtcav23e_inj12_widened_2026-10-15/
  5. when both GPUs are free of RL runs: fine-tune seeds 0, 1 (GPU 0, 1), then seed 2 + the
     from-scratch control. Fixed-epoch cosine, group split with the old flow's split roles,
     selection on val_paired_delta_rms_um.
Every output is a NEW path; nothing existing is overwritten (each step refuses if its output exists).

  nohup python scripts/after_injector_campaign.py > logs/injector_full/after.log 2>&1 &
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
BMAD_PY = "/home/rwu4/miniconda3/envs/bmad-qpad-dev/bin/python"
RL_PY = "/home/rwu4/miniconda3/envs/slac-rl/bin/python"
CAMP = REPO / "data" / "injector_full"
LOG = REPO / "logs" / "injector_full"
PROC = REPO / "processed" / "xtcav23e_inj_2026-10-15.h5"
WIDE = REPO / "trained" / "xtcav23e_inj12_widened_2026-10-15" / "widened.ckpt"
BACKFILL = REPO / "results" / "injector_pilot_2026-10-14" / "campaign_backfill"
FT = {"ft_s0": dict(seed=0, init=True), "ft_s1": dict(seed=1, init=True),
      "ft_s2": dict(seed=2, init=True), "scratch_s0": dict(seed=0, init=False)}


def log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def alive(pid_file: Path) -> bool:
    try:
        os.kill(int(pid_file.read_text().split()[0]), 0)
        return True
    except (OSError, ValueError):
        return False


def env(src=REPO / "src"):
    return {**os.environ, "PYTHONPATH": str(src), "OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1",
            "MKL_NUM_THREADS": "1"}


def wait_campaign():
    while alive(LOG / "run.pid"):
        time.sleep(300)
    tail = (LOG / "run.log").read_text().splitlines()[-5:]
    rows = list(CAMP.glob("sample_*.json"))
    fails = sum(1 for p in rows if not json.loads(p.read_text()).get("success"))
    log(f"campaign driver exited; {len(rows)} sample jsons, {fails} failed; tail: {tail[-1] if tail else ''}")
    if not any(t.startswith("Done:") for t in tail):
        raise SystemExit("campaign did not finish cleanly (no 'Done:'): rerun it to resume; chain stopped")
    if fails > 0.05 * max(len(rows), 1):
        raise SystemExit(f"{fails} failed rows (> 5%): chain stopped for review")


def launch_evalset():
    out_cfg = REPO / "configs" / "datagen" / "injector_evalset_launch.yaml"
    if (REPO / "data" / "injector_evalset").exists():
        log("evalset output exists; not relaunching")
        return
    camp = yaml.safe_load((REPO / "configs" / "datagen" / "injector_full_launch.yaml").read_text())
    cfg = yaml.safe_load((REPO / "configs" / "datagen" / "injector_evalset.yaml").read_text())
    cfg["injector"]["n_particles"] = camp["injector"]["n_particles"]
    cfg["injector"]["grid"] = camp["injector"]["grid"]
    cfg["output_dir"] = str(REPO / "data" / "injector_evalset")
    out_cfg.write_text("# GENERATED by scripts/after_injector_campaign.py: injector_evalset.yaml at the main campaign's\n"
                       f"# fidelity (n_particles {cfg['injector']['n_particles']}, grid {cfg['injector']['grid']}).\n"
                       + yaml.safe_dump(cfg, sort_keys=False))
    subprocess.run(["git", "add", str(out_cfg)], cwd=REPO, check=True)
    subprocess.run(["git", "commit", "-q", "-m", "injector_evalset launch config (campaign fidelity)\n\n"
                    "Co-Authored-By: Claude Opus 5.5 (1M context) <noreply@anthropic.com>"], cwd=REPO, check=True)
    sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True, check=True).stdout.strip()
    wt = REPO / ".worktrees" / f"injector_evalset_{sha[:10]}"
    if not wt.exists():
        subprocess.run(["git", "worktree", "add", "--detach", str(wt), sha], cwd=REPO, check=True)
    elog = REPO / "logs" / "injector_evalset"
    elog.mkdir(parents=True, exist_ok=True)
    with open(elog / "run.log", "a") as f:
        p = subprocess.Popen(["nice", "-n", "10", BMAD_PY, "-u", "-m", "twobunch_s2e_rl.datagen.injector_campaign",
                              str(wt / "configs" / "datagen" / out_cfg.name)], cwd=wt, env=env(wt / "src"),
                             stdout=f, stderr=subprocess.STDOUT, start_new_session=True)
    (elog / "run.pid").write_text(str(p.pid))
    log(f"evalset campaign launched pid {p.pid} (commit {sha[:10]})")


def preprocess():
    if PROC.exists():
        log(f"{PROC} exists; skipping preprocess")
        return
    cmd = [RL_PY, "-m", "twobunch_s2e_rl.surrogate.preprocess",
           "--subdir", "xtcav23_full,xtcav23_pilot,injector_full", "--sweep-set", "xtcav23e_l0b2_inj12",
           "--treaty-point", "XTCAVF", "--transmission", "per_sample", "--P", "1024", "--out", str(PROC),
           # 5e4 (injector_full) vs 1e5 (old campaigns) Bmad macroparticles: the convergence pass rules
           # measured <= 0.11 um spacing / 0.06% sigma_z (results/injector_convergence_2026-10-14)
           "--allow-fixed-mismatch", "num_macro_particles",
           "--campaign-json", f"xtcav23_full={BACKFILL / 'xtcav23_full.json'}",
           "--campaign-json", f"xtcav23_pilot={BACKFILL / 'xtcav23_pilot.json'}"]
    log("preprocess: " + " ".join(cmd[2:]))
    subprocess.run(["nice", "-n", "10", *cmd], cwd=REPO, env=env(), check=True)


def widen():
    if WIDE.exists():
        log(f"{WIDE} exists; skipping widen")
        return
    subprocess.run(["nice", "-n", "10", RL_PY, "scripts/widen_flow_ckpt.py", "--ckpt",
                    "trained/xtcav23/checkpoints/best-*.ckpt", "--norm", str(PROC).replace(".h5", "_norm.json"),
                    "--out", str(WIDE)], cwd=REPO, env=env(), check=True)
    log(f"widened -> {WIDE}")


def gpus_free() -> bool:
    return subprocess.run(["pgrep", "-f", "train_bptt"], capture_output=True).returncode != 0


def finetune(name, gpu, seed, init):
    out = REPO / "trained" / f"xtcav23e_inj_{name}_2026-10-15"
    if out.exists():
        log(f"{out} exists; skipping {name}")
        return None
    args = ["--processed", str(PROC), "--out", str(out), "--split", "group",
            "--orig-split", "processed/xtcav23_combined.h5=xtcav23_full,xtcav23_pilot",
            "--select-metric", "val_paired_delta_rms_um", "--patience", "0", "--seed", str(seed),
            "--lr-schedule", "cosine", "--num-workers", "4"]
    args += (["--init-ckpt", str(WIDE), "--lr", "3e-5", "--epochs", "150"] if init
             else ["--lr", "1e-4", "--epochs", "500"])
    e = {**env(), "CUDA_VISIBLE_DEVICES": str(gpu), "OMP_NUM_THREADS": "2"}
    (REPO / "logs" / "surrogate").mkdir(parents=True, exist_ok=True)
    f = open(REPO / "logs" / "surrogate" / f"xtcav23e_inj_{name}_2026-10-15.log", "w")
    p = subprocess.Popen(["nice", "-n", "5", RL_PY, "-m", "twobunch_s2e_rl.surrogate.train", *args],
                         cwd=REPO, env=e, stdout=f, stderr=subprocess.STDOUT, start_new_session=True)
    log(f"fine-tune {name} on GPU {gpu}: pid {p.pid}")
    return p


def main():
    wait_campaign()
    launch_evalset()
    preprocess()
    widen()
    while not gpus_free():
        time.sleep(300)
    queue = list(FT.items())
    running = {}
    while queue or running:
        for gpu in (0, 1):
            if gpu not in running and queue:
                name, spec = queue.pop(0)
                p = finetune(name, gpu, spec["seed"], spec["init"])
                if p is not None:
                    running[gpu] = (name, p)
        time.sleep(60)
        for gpu, (name, p) in list(running.items()):
            if p.poll() is not None:
                log(f"{name} finished rc={p.returncode}")
                del running[gpu]
    log("chain done")


if __name__ == "__main__":
    sys.exit(main())
